@admin_bp.route("/admin/event/<event_id>/update", methods=["POST"])
@admin_required
@csrf_protect
def update_event(event_id):
    event_id = valid_uuid(event_id)
    if not event_id:
        return "Evento no encontrado", 404

    existing_event = event_service.get_event(event_id)
    if not existing_event:
        return "Evento no encontrado", 404

    currency = clean(request.form.get("currency", "eur"), max_length=3).lower()
    if currency not in VALID_CURRENCIES:
        currency = "eur"

    ticket_types = _parse_ticket_types(request.form, existing_event)
    if not ticket_types:
        return render_template("admin/event_form.html", event=existing_event,
                               error="Anade al menos un tipo de entrada"), 400

    data = {
        "name": clean(request.form.get("name", ""), max_length=200),
        "description": clean(request.form.get("description", ""), max_length=2000),
        "date": clean(request.form.get("date", ""), max_length=30),
        "venue": clean(request.form.get("venue", ""), max_length=200),
        "currency": currency,
        "ticket_types": ticket_types,
    }

    image = request.files.get("image")
    if image and image.filename:
        try:
            data["image_filename"] = event_service.save_image(image)
        except ValueError as e:
            return render_template("admin/event_form.html", event=existing_event, error=str(e))
        if existing_event.get("image_filename"):
            event_service.delete_image(existing_event["image_filename"])

    event_service.update_event(event_id, data)
    return redirect(url_for("admin.event_detail", event_id=event_id))


@admin_bp.route("/admin/import-codes", methods=["POST"])
@admin_required
def import_codes():
    """Parse an Excel file (.xlsx) and return the codes as JSON."""
    file = request.files.get("file")
    if not file or not file.filename:
        return jsonify({"error": "No se ha enviado ningun archivo"}), 400

    filename = file.filename.lower()
    if not filename.endswith((".xlsx", ".xls")):
        return jsonify({"error": "Formato no soportado. Usa un archivo Excel (.xlsx)"}), 400

    try:
        import openpyxl
        wb = openpyxl.load_workbook(file, read_only=True, data_only=True)
        ws = wb.active
        codes = []
        for row in ws.iter_rows(min_col=1, max_col=1, values_only=True):
            val = row[0]
            if val is not None:
                code = str(val).strip().upper()
                if code:
                    codes.append(code)
        wb.close()
    except Exception:
        return jsonify({"error": "Error al leer el archivo Excel"}), 400

    # Deduplicate preserving order
    seen = set()
    unique_codes = []
    for c in codes:
        if c not in seen:
            seen.add(c)
            unique_codes.append(c)

    return jsonify({"codes": unique_codes}), 200


