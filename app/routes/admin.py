@admin_bp.route("/admin/event/create", methods=["POST"])
@admin_required
@csrf_protect
def create_event():
    currency = clean(request.form.get("currency", "eur"), max_length=3).lower()
    if currency not in VALID_CURRENCIES:
        currency = "eur"

    ticket_types = _parse_ticket_types(request.form)
    if not ticket_types:
        return render_template("admin/event_form.html", event=None,
                               error="Anade al menos un tipo de entrada"), 400

    data = {
        "name": clean(request.form.get("name", ""), max_length=200),
        "description": clean(request.form.get("description", ""), max_length=2000),
        "date": clean(request.form.get("date", ""), max_length=30),
        "venue": clean(request.form.get("venue", ""), max_length=200),
        "currency": currency,
        "ticket_types": ticket_types,
    }

    if not data["name"] or not data["date"] or not data["venue"]:
        return render_template("admin/event_form.html", event=None, error="Faltan campos obligatorios"), 400

    image = request.files.get("image")
    if image and image.filename:
        try:
            data["image_filename"] = event_service.save_image(image)
        except ValueError as e:
            return render_template("admin/event_form.html", event=None, error=str(e))

    event_service.create_event(data)
    return redirect(url_for("admin.dashboard"))


@admin_bp.route("/admin/event/<event_id>")
@admin_required
def event_detail(event_id):
    event_id = valid_uuid(event_id)
    if not event_id:
        return "Evento no encontrado", 404
    event = event_service.get_event(event_id)
    if not event:
        return "Evento no encontrado", 404
    stats = ticket_service.get_event_stats(event_id)
    available = event_service.get_total_available(event)
    total_capacity = event_service.get_total_capacity(event)
    total_sold = event_service.get_total_sold(event)
    recent = ticket_service.get_recent_purchases(event_id)
    return render_template(
        "admin/event_detail.html",
        event=event,
        stats=stats,
        available=available,
        total_capacity=total_capacity,
        total_sold=total_sold,
        recent=recent,
    )


