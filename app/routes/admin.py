admin_bp = Blueprint("admin", __name__)

VALID_CURRENCIES = {"eur", "usd", "gbp"}


def admin_required(f):
    @wraps(f)
    def decorated(*args, **kwargs):
        if not session.get("admin_authenticated"):
            return redirect(url_for("admin.login"))
        return f(*args, **kwargs)
    return decorated


def _parse_ticket_types(form, existing_event=None):
    """Parse ticket types from form data.

    Form fields: type_name[], type_price[], type_max_tickets[], type_id[],
                 access_codes_enabled[], access_codes_reusable[], access_codes_list[]
    """
    names = form.getlist("type_name[]")
    prices = form.getlist("type_price[]")
    max_tickets_list = form.getlist("type_max_tickets[]")
    type_ids = form.getlist("type_id[]")
    ac_enabled_list = form.getlist("access_codes_enabled[]")
    ac_reusable_list = form.getlist("access_codes_reusable[]")
    ac_codes_list = form.getlist("access_codes_list[]")

    # Build lookup for existing sold/reserved counters and access codes
    existing = {}
    if existing_event:
        for tt in existing_event.get("ticket_types", []):
            existing[tt["type_id"]] = tt

    ticket_types = []
    for i in range(len(names)):
        name = clean(names[i], max_length=100)
        price = valid_float(prices[i] if i < len(prices) else 0, min_val=0.0)
        max_t = valid_int(max_tickets_list[i] if i < len(max_tickets_list) else 1, min_val=1, max_val=100000, default=1)
        type_id = type_ids[i].strip() if i < len(type_ids) and type_ids[i].strip() else ""

        if not name:
            continue

        # Preserve sold/reserved from existing type
        prev = existing.get(type_id, {})

        entry = {
            "type_id": type_id or None,  # None = new, will be generated by model
            "name": name,
            "price": price,
            "max_tickets": max_t,
            "tickets_sold": prev.get("tickets_sold", 0),
            "tickets_reserved": prev.get("tickets_reserved", 0),
        }

        # Access codes
        ac_enabled = (ac_enabled_list[i] if i < len(ac_enabled_list) else "0") == "1"
        ac_reusable = (ac_reusable_list[i] if i < len(ac_reusable_list) else "0") == "1"
        ac_raw = ac_codes_list[i] if i < len(ac_codes_list) else ""

        if ac_enabled:
            # Parse, sanitize, and normalize codes to uppercase
            raw_codes = [clean(c, max_length=100).strip().upper() for c in ac_raw.split("\n")]
            raw_codes = [c for c in raw_codes if c]  # Remove empty
            raw_codes = list(dict.fromkeys(raw_codes))  # Remove duplicates, preserve order

            if ac_reusable:
                access_codes = [{"code": raw_codes[0], "used": False}] if raw_codes else []
            else:
                # Preserve used codes from existing data
                used_codes = [ac for ac in prev.get("access_codes", []) if ac.get("used")]
                used_code_set = {ac["code"] for ac in used_codes}
                new_codes = [{"code": c, "used": False} for c in raw_codes if c not in used_code_set]
                access_codes = used_codes + new_codes

            entry["access_codes_enabled"] = True
            entry["access_codes_reusable"] = ac_reusable
            entry["access_codes"] = access_codes
        else:
            entry["access_codes_enabled"] = False
            entry["access_codes_reusable"] = False
            entry["access_codes"] = []

        ticket_types.append(entry)

    return ticket_types


@admin_bp.route("/admin/login", methods=["GET", "POST"])
@limiter.limit("5 per minute", methods=["POST"])
@csrf_protect
def login():
    if request.method == "POST":
        password = request.form.get("password", "")
        if password == current_app.config["ADMIN_PASSWORD"]:
            session.permanent = True
            session["admin_authenticated"] = True
            return redirect(url_for("admin.dashboard"))
        return render_template("admin/login.html", error="Contrasena incorrecta")
    return render_template("admin/login.html")


@admin_bp.route("/admin/logout")
def logout():
    session.pop("admin_authenticated", None)
    return redirect(url_for("main.index"))


